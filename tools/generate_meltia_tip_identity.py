"""Render the C# TIP identity from the T2 manifest; --check is read-only."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "config/tsf/meltia-t2-identity.json"
DEST = ROOT / "src/Meltype/Tip/Meltia.Generated/MeltiaTipIdentity.g.cs"


def render(manifest):
    ident = manifest["identity"]
    ipc = manifest["ipc"]
    if manifest["registrationEnabled"] is not False or any(manifest["deployment"].values()):
        raise ValueError("T3b only supports an unregistered identity manifest")
    if ipc["requireVersionHandshake"] is not True or manifest["protocolVersion"] != 1:
        raise ValueError("Meltia T3b wire is v1 only")
    return (
        "// <auto-generated> tools/generate_meltia_tip_identity.py; do not hand edit.\n"
        "// SPDX-License-Identifier: GPL-3.0-or-later\n"
        "namespace Meltype.Tip;\n\n"
        "internal static class MeltiaTipIdentity\n"
        "{\n"
        f"    internal const int ProtocolVersion = {manifest['protocolVersion']};\n"
        f"    internal const string PipePrefix = \"{ipc['pipePrefix']}\";\n"
        f"    internal const string Clsid = \"{ident['clsid']}\";\n"
        f"    internal const string ProfileGuid = \"{ident['profileGuid']}\";\n"
        "}\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = render(json.loads(SOURCE.read_text(encoding="utf-8")))
    if args.check:
        if not DEST.exists() or DEST.read_text(encoding="utf-8") != content:
            parser.error("C# generated identity is stale; regenerate from the T2 manifest")
        print("PASS: C# TIP constants match T2 identity manifest")
    else:
        DEST.write_text(content, encoding="utf-8")
        print(DEST)


if __name__ == "__main__":
    main()
