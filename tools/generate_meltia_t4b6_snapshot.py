"""Generate a temporary, manifest-bound C++ snapshot for the isolated T4-B6 observer.

Reads the ONE T2 manifest in this repository. Validates T2's design-only /
registration-disabled policy BEFORE producing C++ which binds the observer's
runtime GUIDs and exact manifest bytes. It never registers TSF or invokes COM.
"""
import argparse
import json
from pathlib import Path
from uuid import UUID

from meltia_t4a_preflight import MANIFEST, ROOT, validate_preflight_manifest

FIELDS = ("clsid", "inputAttributeGuid", "convertedAttributeGuid", "targetAttributeGuid")
HEADER_NAME = "MeltiaT4b6IdentitySnapshot.h"
RAW_DELIMITER = "T4B6T2SNAP"


def reject_duplicate_pairs(pairs):
    out = {}
    for key, value in pairs:
        if key in out:
            raise ValueError("duplicate manifest JSON key")
        out[key] = value
    return out


def generate(raw):
    if not isinstance(raw, bytes) or len(raw) > 131072 or not raw:
        raise ValueError("invalid manifest size")
    manifest = json.loads(raw.decode("utf-8"), object_pairs_hook=reject_duplicate_pairs)
    ids = validate_preflight_manifest(manifest)
    # The exact file bytes are bound to this generated header, and a live
    # observer refuses any manifest whose bytes have changed since compilation.
    # This also catches changed deployment flags or stale binaries.
    manifest_text = raw.decode("utf-8")
    if ")" + RAW_DELIMITER + '"' in manifest_text:
        raise ValueError("manifest cannot be represented in raw C++ literal")
    guid_literals = ",\n    ".join('L"{' + str(UUID(ids[key])).upper() + '}"' for key in FIELDS)
    return (
        "// Generated by generate_meltia_t4b6_snapshot.py; not checked in.\n"
        "// T2 validated design-only/registration-disabled snapshot.\n"
        "#pragma once\n"
        "namespace meltia_t4b6_identity {\n"
        "inline constexpr wchar_t const* kExpectedGuids[4] = {\n    "
        + guid_literals + "\n};\n"
        "inline constexpr char kManifestBytes[] = R\"" + RAW_DELIMITER + "("
        + manifest_text + ")" + RAW_DELIMITER + "\";\n"
        "}\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    output = args.output.resolve()
    root = ROOT.resolve()
    if output.name != HEADER_NAME or output == root or root in output.parents:
        parser.error("snapshot must be an external temporary header with the expected basename")
    if output.exists():
        parser.error("refusing to overwrite an existing snapshot")
    try:
        generated = generate(MANIFEST.read_bytes())
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(generated, encoding="utf-8")
    except (OSError, UnicodeError, ValueError, TypeError, KeyError) as exc:
        parser.error("T2 snapshot cannot be generated: " + str(exc))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
